def _atomic_write_json(path: Path, payload: Mapping[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(
        json.dumps(payload, indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    temporary.replace(path)


def _load_oracle(path: Path) -> OracleArchive:
    """Load one archive and canonicalise all axes to ascending wavelength."""

    source = path.expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(
            f"missing pRT H-minus oracle {source}; run the pRT generator first"
        )
    with np.load(source, allow_pickle=False) as archive:
        required = (
            "metadata_json",
            "pressure_bar",
            "temperature_reference_K",
            "temperature_profile_K",
            "gravity_m_s2",
            "wavelength_micron",
            "frequency_centers_hz",
            "frequency_bin_edges_hz",
            "wavelength_bin_edges_micron",
            "flux_w_m2_m",
        )
        missing = [key for key in required if key not in archive.files]
        if missing:
            raise ValueError(f"oracle {source} is missing keys: {', '.join(missing)}")
        metadata = json.loads(str(archive["metadata_json"]))
        pressure = np.asarray(archive["pressure_bar"], dtype=float)
        temperature_reference = np.asarray(
            archive["temperature_reference_K"], dtype=float
        )
        temperature_profile = np.asarray(archive["temperature_profile_K"], dtype=float)
        gravity = np.asarray(archive["gravity_m_s2"], dtype=float)
        wavelength = np.asarray(archive["wavelength_micron"], dtype=float)
        frequency = np.asarray(archive["frequency_centers_hz"], dtype=float)
        frequency_edges = np.asarray(archive["frequency_bin_edges_hz"], dtype=float)
        wavelength_edges = np.asarray(
            archive["wavelength_bin_edges_micron"], dtype=float
        )
        flux = np.asarray(archive["flux_w_m2_m"], dtype=float)

    if wavelength.ndim != 1 or wavelength.size < 2:
        raise ValueError("oracle wavelength axis must have at least two samples")
    if wavelength[0] > wavelength[-1]:
        wavelength = wavelength[::-1]
        frequency = frequency[::-1]
        flux = flux[..., ::-1]
    if wavelength_edges[0] > wavelength_edges[-1]:
        wavelength_edges = wavelength_edges[::-1]
    if wavelength_edges.size != wavelength.size + 1:
        raise ValueError("oracle wavelength-bin edges must have n+1 samples")
    if frequency_edges.size != wavelength.size + 1:
        raise ValueError("oracle frequency-bin edges must have n+1 samples")
    if not np.all(np.diff(wavelength) > 0.0):
        raise ValueError("oracle wavelength samples must be strictly increasing")
    if not np.all(np.diff(wavelength_edges) > 0.0):
        raise ValueError("oracle wavelength-bin edges must be strictly increasing")
    if flux.shape != (3, 2, len(MODES), wavelength.size):
        raise ValueError(
            "oracle flux must have shape (temperature, gravity, mode, wavelength)"
        )
    if pressure.ndim != 1 or temperature_profile.shape != (
        temperature_reference.size,
        pressure.size,
    ):
        raise ValueError("oracle pressure and temperature arrays have invalid shapes")
    return OracleArchive(
        path=source,
        metadata=metadata,
        pressure_bar=pressure,
        temperature_reference_K=temperature_reference,
        temperature_profile_K=temperature_profile,
        gravity_m_s2=gravity,
        wavelength_micron=wavelength,
        frequency_centers_hz=frequency,
        frequency_bin_edges_hz=frequency_edges,
        wavelength_bin_edges_micron=wavelength_edges,
        flux_w_m2_m=flux,
    )


def _spectral_grid(archive: OracleArchive, name: str) -> SpectralGrid:
    return SpectralGrid(
        values=archive.wavelength_micron,
        bin_edges=archive.wavelength_bin_edges_micron,
        unit="micron",
        role="opacity",
        name=name,
        metadata={
            "frequency_bin_edges_source": "petitRADTRANS Radtrans._frequency_bins_edges",
            "frequency_bin_edges_unit": "Hz",
        },
    )


def _pressure_grid(archive: OracleArchive) -> PressureGrid:
    grid = PressureGrid.from_log_centers(
        float(archive.pressure_bar[0]),
        float(archive.pressure_bar[-1]),
        int(archive.pressure_bar.size),
        unit="bar",
        name="pRT H-minus oracle pressure centers",
    )
    if not np.allclose(grid.centers, archive.pressure_bar, rtol=2.0e-13, atol=0.0):
        raise ValueError("oracle pressure centers are not logarithmically reproducible")
    return grid


def _robert_vmr(state: oracle.VMRState) -> dict[str, float]:
    """Return the complete state with ROBERT's ``CO`` key and VMR values."""

    values = state.vmr
    return {
        "H2": values["H2"],
        "He": values["He"],
        "CO": values["CO__HITEMP"],
        "H-": values["H-"],
        "H": values["H"],
        "e-": values["e-"],
    }


def _robert_mmw(vmr: Mapping[str, float]) -> float:
    result = sum(float(vmr[name]) * ROBERT_MOLAR_MASSES_AMU[name] for name in vmr)
    if not np.isfinite(result) or result <= 0.0:
        raise ValueError("ROBERT VMR state has an invalid mean molecular weight")
    return float(result)


def _atmosphere(
    archive: OracleArchive,
    temperature_reference_K: float,
    state: oracle.VMRState,
) -> AtmosphereState:
    pressure_grid = _pressure_grid(archive)
    temperature = float(temperature_reference_K) + (
        oracle.TEMPERATURE_GRADIENT_K_PER_DECADE * np.log10(archive.pressure_bar)
    )
    if not np.all(temperature > 0.0):
        raise ValueError("benchmark temperature profile is not positive")
    vmr = _robert_vmr(state)
    profiles = {
        species: np.full(pressure_grid.n_layers, value, dtype=float)
        for species, value in vmr.items()
    }
    return AtmosphereState(
        pressure_grid=pressure_grid,
        temperature=temperature,
        composition=profiles,
        mean_molecular_weight=np.full(
            pressure_grid.n_layers,
            _robert_mmw(vmr),
            dtype=float,
        ),
        metadata={
            "composition_source": "explicit VMR benchmark state",
            "vmr_mode": state.mode,
            "mass_fraction_conversion": "none in ROBERT",
        },
    )


